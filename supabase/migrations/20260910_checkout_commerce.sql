CREATE OR REPLACE FUNCTION public.generate_order_number()
RETURNS trigger
LANGUAGE plpgsql
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_prefix text;
BEGIN
  IF NEW.order_number IS NULL OR NEW.order_number = '' THEN
    SELECT coalesce(
      nullif(trim(s.setting_value #>> '{}'), ''),
      'SS'
    )
    INTO v_prefix
    FROM public.settings s
    WHERE (s.category = 'orders' AND s.setting_key = 'order_prefix')
       OR (s.category = 'general' AND s.setting_key = 'order_prefix')
    ORDER BY CASE WHEN s.category = 'orders' THEN 0 ELSE 1 END
    LIMIT 1;

    v_prefix := regexp_replace(coalesce(v_prefix, 'SS'), '[^A-Za-z0-9]', '', 'g');
    IF v_prefix = '' THEN
      v_prefix := 'SS';
    END IF;

    NEW.order_number :=
      upper(v_prefix) || '-' ||
      lpad(nextval('order_number_seq')::text, 6, '0');
  END IF;

  RETURN NEW;
END;
$function$;

