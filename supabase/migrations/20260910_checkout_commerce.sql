CREATE OR REPLACE FUNCTION public.save_mpesa_provider(
  p_environment text,
  p_consumer_key text,
  p_consumer_secret text,
  p_shortcode text,
  p_passkey text,
  p_party_type text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'private'
AS $function$
DECLARE
  v_env text;
  v_type text;
BEGIN
  IF NOT public.is_staff() THEN
    RAISE EXCEPTION 'Only staff can save M-Pesa settings';
  END IF;

  v_env := CASE WHEN lower(trim(coalesce(p_environment, ''))) = 'production' THEN 'production' ELSE 'sandbox' END;
  v_type := CASE WHEN lower(trim(coalesce(p_party_type, ''))) = 'paybill' THEN 'paybill' ELSE 'till' END;

  INSERT INTO private.mpesa_provider_config (
    id, environment, consumer_key, consumer_secret, shortcode, passkey, party_type, updated_at
  )
  VALUES (
    1,
    v_env,
    nullif(trim(p_consumer_key), ''),
    CASE
      WHEN coalesce(trim(p_consumer_secret), '') = '' THEN (
        SELECT consumer_secret FROM private.mpesa_provider_config WHERE id = 1
      )
      ELSE trim(p_consumer_secret)
    END,
    nullif(trim(p_shortcode), ''),
    CASE
      WHEN coalesce(trim(p_passkey), '') = '' THEN (
        SELECT passkey FROM private.mpesa_provider_config WHERE id = 1
      )
      ELSE trim(p_passkey)
    END,
    v_type,
    now()
  )
  ON CONFLICT (id) DO UPDATE
    SET environment = excluded.environment,
        consumer_key = excluded.consumer_key,
        consumer_secret = excluded.consumer_secret,
        shortcode = excluded.shortcode,
        passkey = excluded.passkey,
        party_type = excluded.party_type,
        updated_at = now();

  RETURN jsonb_build_object('ok', true);
END;
$function$;

