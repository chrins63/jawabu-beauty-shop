CREATE OR REPLACE FUNCTION public.prepare_mpesa_stk(
  p_order_id integer,
  p_contact_phone text,
  p_mpesa_phone text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_contact text;
  v_phone text;
  v_order public.orders%ROWTYPE;
  v_payment public.payments%ROWTYPE;
BEGIN
  v_contact := public.normalize_ke_phone(p_contact_phone);
  v_phone := public.normalize_ke_phone(coalesce(nullif(trim(p_mpesa_phone), ''), p_contact_phone));

  IF v_contact IS NULL OR v_phone IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'error', 'Enter a valid M-Pesa number');
  END IF;

  SELECT * INTO v_order
  FROM public.orders
  WHERE id = p_order_id
    AND public.normalize_ke_phone(phone) = v_contact;

  IF v_order.id IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'error', 'Order not found');
  END IF;

  IF lower(coalesce(v_order.payment_status, '')) IN ('paid', 'completed', 'success') THEN
    RETURN jsonb_build_object(
      'ok', true,
      'already_paid', true,
      'order_number', v_order.order_number,
      'amount', ceil(v_order.total_amount)
    );
  END IF;

  SELECT * INTO v_payment
  FROM public.payments
  WHERE order_id = v_order.id
  ORDER BY id DESC
  LIMIT 1;

  IF v_payment.stk_requested_at IS NOT NULL
     AND v_payment.stk_requested_at > now() - interval '20 seconds' THEN
    RETURN jsonb_build_object(
      'ok', false,
      'error', 'A payment prompt was just sent. Wait a moment before trying again.'
    );
  END IF;

  UPDATE public.payments
  SET phone = v_phone,
      stk_requested_at = now(),
      updated_at = now()
  WHERE id = v_payment.id;

  RETURN jsonb_build_object(
    'ok', true,
    'already_paid', false,
    'order_id', v_order.id,
    'order_number', v_order.order_number,
    'amount', ceil(v_order.total_amount)::integer,
    'msisdn', replace(v_phone, '+', ''),
    'account_reference', left(regexp_replace(v_order.order_number, '[^A-Za-z0-9]', '', 'g'), 12)
  );
END;
$function$;

CREATE OR REPLACE FUNCTION public.complete_mpesa_stk(
  p_checkout_request_id text,
  p_merchant_request_id text,
  p_result_code integer,
  p_result_desc text,
  p_receipt text,
  p_payload jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_payment public.payments%ROWTYPE;
BEGIN
  IF nullif(trim(p_checkout_request_id), '') IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'error', 'Missing checkout request');
  END IF;

  SELECT * INTO v_payment
  FROM public.payments
  WHERE checkout_request_id = trim(p_checkout_request_id)
  LIMIT 1;

  IF v_payment.id IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'error', 'Unknown checkout request');
  END IF;

  IF p_result_code = 0 THEN
    UPDATE public.payments
    SET
      status = 'paid',
      transaction_id = coalesce(nullif(trim(p_receipt), ''), transaction_id),
      merchant_request_id = coalesce(nullif(trim(p_merchant_request_id), ''), merchant_request_id),
      result_desc = coalesce(p_result_desc, 'Paid'),
      mpesa_payload = coalesce(p_payload, mpesa_payload),
      updated_at = now()
    WHERE id = v_payment.id;

    UPDATE public.orders
    SET
      payment_status = 'paid',
      transaction_id = coalesce(nullif(trim(p_receipt), ''), transaction_id),
      updated_at = now()
    WHERE id = v_payment.order_id;

    RETURN jsonb_build_object('ok', true, 'paid', true, 'order_id', v_payment.order_id);
  END IF;

  UPDATE public.payments
  SET
    result_desc = coalesce(p_result_desc, 'Payment not completed'),
    merchant_request_id = coalesce(nullif(trim(p_merchant_request_id), ''), merchant_request_id),
    mpesa_payload = coalesce(p_payload, mpesa_payload),
    updated_at = now()
  WHERE id = v_payment.id;

  RETURN jsonb_build_object('ok', true, 'paid', false, 'order_id', v_payment.order_id);
END;
$function$;

